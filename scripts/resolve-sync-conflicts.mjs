#!/usr/bin/env node

import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const REPO = 'workos/openapi-spec';
const MARKER = '.last-synced-sha';
const SHA = /^[a-f0-9]{40}$/;

function git(cwd, args, options = {}) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, ...options });
}

function api(endpoint, data, token = process.env.GH_TOKEN) {
  return JSON.parse(execFileSync('gh', [
    'api', endpoint, ...(data ? ['--method', 'POST', '--input', '-'] : []),
  ], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    input: data ? JSON.stringify(data) : undefined,
    env: { ...process.env, ...(token ? { GH_TOKEN: token } : {}) },
  }));
}

export function eligible(pr) {
  return pr.state === 'open'
    && !pr.draft
    && pr.user?.login === 'workos-sdk-automation[bot]'
    && pr.head?.repo?.full_name === REPO
    && pr.base?.repo?.full_name === REPO
    && pr.base.ref === 'main'
    && /^update-spec-/.test(pr.head.ref)
    && pr.labels.some((label) => label.name === 'autogenerated');
}

export function newerSha(base, head, status) {
  if (!SHA.test(base) || !SHA.test(head)) throw new Error('Invalid source SHA');
  if (base === head) return base;
  if (status === 'ahead') return head;
  if (status === 'behind') return base;
  throw new Error(`Cannot order source SHAs: ${status}`);
}

// merge-tree and a temporary index never check out or execute PR-controlled files.
export function mergeConflict(cwd, head, base) {
  if (!SHA.test(head) || !SHA.test(base)) throw new Error('Invalid PR commit SHA');
  const result = spawnSync('git', ['merge-tree', '--write-tree', '--name-only', '-z', head, base], {
    cwd, encoding: 'utf8',
  });
  if (result.error) throw result.error;
  if (result.status === 0) return null;
  if (result.status !== 1) throw new Error(result.stderr || 'git merge-tree failed');
  const [tree, ...fields] = result.stdout.split('\0');
  const conflicts = fields.slice(0, fields.indexOf(''));
  if (conflicts.length !== 1 || conflicts[0] !== MARKER) {
    console.log(`Leaving code conflicts for manual review: ${conflicts.join(', ')}`);
    return null;
  }
  const baseSource = git(cwd, ['show', `${base}:${MARKER}`]).trim();
  const headSource = git(cwd, ['show', `${head}:${MARKER}`]).trim();
  if (!SHA.test(baseSource) || !SHA.test(headSource)) throw new Error('Invalid source SHA');
  return { tree, baseSource, headSource };
}

export function resolveTree(cwd, tree, markerCommit) {
  const dir = mkdtempSync(join(tmpdir(), 'sync-index-'));
  const env = { ...process.env, GIT_INDEX_FILE: join(dir, 'index') };
  try {
    git(cwd, ['read-tree', tree], { env });
    const blob = git(cwd, ['rev-parse', `${markerCommit}:${MARKER}`]).trim();
    git(cwd, ['update-index', '--cacheinfo', `100644,${blob},${MARKER}`], { env });
    return git(cwd, ['write-tree'], { env }).trim();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function uploadTree(cwd, head, tree) {
  const fields = git(cwd, ['diff', '--raw', '--no-abbrev', '--no-renames', '-z', head, tree]).split('\0');
  const entries = [];
  for (let i = 0; i < fields.length - 1; i += 2) {
    const [oldMode, mode, , sha] = fields[i].slice(1).split(' ');
    const deleted = mode === '000000';
    const type = (deleted ? oldMode : mode) === '160000' ? 'commit' : 'blob';
    if (!deleted && type === 'blob') {
      const content = git(cwd, ['cat-file', 'blob', sha], { encoding: 'buffer' }).toString('base64');
      api(`repos/${REPO}/git/blobs`, { content, encoding: 'base64' });
    }
    entries.push({ path: fields[i + 1], mode: deleted ? oldMode : mode, type, sha: deleted ? null : sha });
  }
  const result = api(`repos/${REPO}/git/trees`, {
    base_tree: git(cwd, ['rev-parse', `${head}^{tree}`]).trim(), tree: entries,
  });
  if (result.sha !== tree) throw new Error('Uploaded merge tree does not match local resolution');
  return result.sha;
}

function publish(cwd, pr, base, tree) {
  const uploaded = uploadTree(cwd, pr.head.sha, tree);
  // Omitting author/committer lets GitHub sign as the installation-token bot.
  const commit = api(`repos/${REPO}/git/commits`, {
    message: 'fix(ci): resolve synced SHA conflict with main',
    tree: uploaded,
    parents: [pr.head.sha, base],
  });
  if (!commit.verification?.verified) throw new Error('Refusing to publish an unsigned merge commit');
  const current = api(`repos/${REPO}/pulls/${pr.number}`);
  const currentBase = api(`repos/${REPO}/git/ref/heads/main`).object.sha;
  if (!eligible(current) || current.head.sha !== pr.head.sha || currentBase !== base) {
    throw new Error(`PR #${pr.number} changed during resolution; rerun against its current state`);
  }
  // A non-forced ref update rejects concurrent pushes instead of overwriting them.
  execFileSync('gh', ['api', '--method', 'PATCH', `repos/${REPO}/git/refs/heads/${pr.head.ref}`, '--input', '-'], {
    input: JSON.stringify({ sha: commit.sha, force: false }), stdio: ['pipe', 'inherit', 'inherit'],
  });
}

function resolvePr(pr, write) {
  if (!eligible(pr)) return;
  const cwd = process.cwd();
  // PR metadata can retain the base SHA from creation, not today's main tip.
  const base = api(`repos/${REPO}/git/ref/heads/main`).object.sha;
  if (!SHA.test(pr.head.sha) || !SHA.test(base)) throw new Error('Invalid PR commit SHA');
  git(cwd, ['fetch', '--no-tags', 'origin', pr.head.sha, base]);
  const conflict = mergeConflict(cwd, pr.head.sha, base);
  if (!conflict) {
    console.log(`#${pr.number}: no SHA-only conflict to resolve`);
    return;
  }
  const { baseSource, headSource } = conflict;
  const comparison = api(`repos/workos/workos/compare/${baseSource}...${headSource}`, undefined, process.env.SOURCE_GH_TOKEN);
  const newest = newerSha(baseSource, headSource, comparison.status);
  const tree = resolveTree(cwd, conflict.tree, newest === headSource ? pr.head.sha : base);
  console.log(`#${pr.number}: ${write ? 'Resolving' : 'Would resolve'} ${MARKER} to ${newest} (tree ${tree})`);
  if (write) publish(cwd, pr, base, tree);
}

function main() {
  const { values } = parseArgs({ options: { pr: { type: 'string' }, write: { type: 'boolean', default: false } } });
  if (values.pr && !/^[1-9]\d*$/.test(values.pr)) throw new Error('Expected a positive PR number');
  const prs = values.pr
    ? [api(`repos/${REPO}/pulls/${values.pr}`)]
    : JSON.parse(execFileSync('gh', ['api', '--paginate', '--slurp', `repos/${REPO}/pulls?state=open&base=main&per_page=100`], {
      encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
    })).flat();
  for (const pr of prs) {
    try {
      resolvePr(pr, values.write);
    } catch (error) {
      console.error(`#${pr.number}: ${error.message}`);
      process.exitCode = 1;
    }
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
